"""Write the Badman profile's identity, code-range and font-relocation facts as
a C++ header for the native preparation tool (badman_prepare). The facts are
addresses, sizes, masks and hashes from config/; no game code or asset bytes.
"""
import argparse
import csv
import json
from pathlib import Path

PROFILE = Path(__file__).resolve().parents[1]


def number(value):
    return int(value, 0) if isinstance(value, str) else int(value)


def ranges(path):
    with path.open(encoding='utf-8-sig', newline='') as handle:
        return [(number(row['address']), number(row['size'])) for row in csv.DictReader(handle)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    config = PROFILE / 'config'
    executable = json.loads((config / 'executable.json').read_text(encoding='utf-8'))
    font = json.loads((config / 'font_module.json').read_text(encoding='utf-8'))
    recipe = json.loads((config / 'font_relocations.json').read_text(encoding='utf-8'))
    if recipe['schema'] != 1 or recipe['algorithm'] != 'masked_modular_addition' or recipe['source_sha256'] != font['unpacked_sha256']:
        raise SystemExit('Unsupported font relocation recipe')
    lines = ['// Generated by tools/embed_profile_facts.py from profiles/badman/config. Do not edit.',
             '#pragma once', '#include <array>', '#include <cstdint>', '#include <string_view>',
             'namespace badman::facts {',
             f'inline constexpr std::string_view disc_id = "{executable["disc_id"]}";',
             f'inline constexpr std::string_view disc_version = "{executable["disc_version"]}";',
             f'inline constexpr std::string_view iso_sha256 = "{executable["iso_sha256"]}";',
             f'inline constexpr std::uint64_t iso_size = {number(executable["iso_size"])}ull;',
             f'inline constexpr std::string_view elf_sha256 = "{executable["elf_sha256"]}";',
             f'inline constexpr std::string_view font_module = "{font["module"]}";',
             f'inline constexpr std::string_view font_input_sha256 = "{font["input_sha256"]}";',
             f'inline constexpr std::string_view font_unpacked_sha256 = "{font["unpacked_sha256"]}";',
             f'inline constexpr std::string_view font_prepared_sha256 = "{font["prepared_sha256"]}";',
             f'inline constexpr std::uint32_t font_load_base = 0x{number(font["load_base"]):08X}u;',
             f'inline constexpr std::uint32_t font_gp = 0x{number(font["gp"]):08X}u;',
             f'inline constexpr std::uint32_t font_entry = 0x{number(font["entry"]):08X}u;',
             f'inline constexpr std::uint32_t font_module_info_relative = 0x{number(font["module_info_relative"]):X}u;',
             'struct Segment { std::uint32_t vaddr, filesz, memsz, flags; std::string_view sha256; };',
             'inline constexpr std::array font_segments{']
    for row in font['snapshots']:
        lines.append(f'    Segment{{0x{number(row["vaddr"]):X}u, 0x{number(row["filesz"]):X}u, 0x{number(row["memsz"]):X}u, '
                     f'0x{number(row["flags"]):X}u, "{row["sha256"]}"}},')
    lines += ['};', 'struct Export { std::string_view library; std::uint32_t nid, address_relative; bool function; };',
              'inline constexpr std::array font_exports{']
    for row in font['exports']:
        lines.append(f'    Export{{"{row["library"]}", 0x{number(row["nid"]):08X}u, 0x{number(row["address_relative"]):X}u, '
                     f'{"true" if row["kind"] == "function" else "false"}}},')
    lines += ['};', 'struct Import { std::string_view library; std::uint32_t nid, stub_relative; };',
              'inline constexpr std::array font_imports{']
    for row in font['imports']:
        lines.append(f'    Import{{"{row["library"]}", 0x{number(row["nid"]):08X}u, 0x{number(row["stub_relative"]):X}u}},')
    lines += ['};', 'struct Relocation { std::uint32_t segment, offset, mask, addend; };',
              f'inline constexpr std::uint32_t font_relocation_base = 0x{number(recipe["load_base"]):08X}u;',
              'inline constexpr std::array font_relocations{']
    for row in recipe['operations']:
        lines.append(f'    Relocation{{{number(row["segment"])}u, 0x{number(row["offset"]):X}u, '
                     f'0x{number(row["mask"]):08X}u, 0x{number(row["addend"]):X}u}},')
    lines += ['};', 'struct Range { std::uint32_t address, size; };', 'inline constexpr std::array code_ranges{']
    lines += [f'    Range{{0x{a:08X}u, 0x{s:X}u}},' for a, s in ranges(config / 'code_ranges.csv')]
    lines += ['};', 'inline constexpr std::array font_code_ranges{']
    lines += [f'    Range{{0x{a:08X}u, 0x{s:X}u}},' for a, s in ranges(config / 'font_code_ranges.csv')]
    lines += ['};', '}', '']
    text = '\n'.join(lines)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text(encoding='utf-8') != text:
        args.output.write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
